def test_lockfiles_pin_transitive_deps_with_hashes():
    """Committed requirements.lock + requirements-dev.lock pin == with sha256 hashes."""
    runtime = _lock_entries(RUNTIME_LOCK)
    dev = _lock_entries(DEV_LOCK)
    for name, (version, _digest) in runtime.items():
        assert name in dev, f"{name} in requirements.lock but missing from requirements-dev.lock"
        assert dev[name][0] == version, (
            f"{name} version mismatch: runtime {version} vs dev {dev[name][0]}"
        )


def test_every_lock_entry_carries_an_exact_version_and_hash():
    for path in (RUNTIME_LOCK, DEV_LOCK):
        text = path.read_text(encoding="utf-8")
        requirement_lines = [
            line
            for line in text.splitlines()
            if line.strip() and not line.lstrip().startswith(("#", "--hash="))
        ]
        assert len(requirement_lines) == len(_lock_entries(path)), (
            f"{path.name}: every non-comment line must parse as a hash-pinned "
            "requirement; a line that does not is an unpinned install"
        )


def test_lock_pins_every_direct_requirement():
    """Nothing the floors declare may be absent from the matching lock."""
    runtime = _lock_entries(RUNTIME_LOCK)
    dev = _lock_entries(DEV_LOCK)
    for name, lock in (("requirements.txt", runtime), ("requirements-dev.txt", dev)):
        direct = set()
        for line in (REPO / name).read_text(encoding="utf-8").splitlines():
            line = line.split("#", 1)[0].strip()
            if not line or line.startswith("-r"):
                continue
            match = re.match(r"^([A-Za-z0-9_.-]+)", line)
            assert match, f"unparseable requirement in {name}: {line!r}"
            direct.add(match.group(1).lower().replace("_", "-"))
        missing = sorted(direct - set(lock))
        assert not missing, f"direct requirements absent from {name}'s lock: {missing}"


def test_lock_pins_are_not_below_requirements_floors():
    """Exact lock versions must never be looser than requirements.txt floors."""
    locked = _lock_entries(RUNTIME_LOCK)
    for line in (REPO / "requirements.txt").read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line or line.startswith("-r") or ">=" not in line:
            continue
        package, floor = line.split(">=", 1)
        key = package.strip().lower().replace("_", "-")
        pinned = locked[key][0]
        assert _version_tuple(pinned) >= _version_tuple(floor.strip()), (
            f"{key} is locked at {pinned}, below its declared floor {floor.strip()}"
        )


def test_lock_satisfies_the_declared_floors():
    """Dev lock may be stricter than floors, never looser."""
    locked = _lock_entries(DEV_LOCK)
    for name in ("requirements.txt", "requirements-dev.txt"):
        for line in (REPO / name).read_text(encoding="utf-8").splitlines():
            line = line.split("#", 1)[0].strip()
            if not line or line.startswith("-r") or ">=" not in line:
                continue
            package, floor = line.split(">=", 1)
            # Strip trailing upper bounds like ",<2" if ever present.
            floor_ver = floor.strip().split(",")[0].strip()
            key = package.strip().lower().replace("_", "-")
            pinned = locked[key][0]
            assert _version_tuple(pinned) >= _version_tuple(floor_ver), (
                f"{key} is locked at {pinned}, below its declared floor {floor_ver}"
            )


def test_lock_versions_satisfy_every_declared_bound():
    """A floor is half a requirement; the ceiling is the other half.

    `test_lock_satisfies_the_declared_floors` above strips upper bounds by
    design, so nothing ever compared a locked version against a ceiling.
    Narrowing one without regenerating leaves a lock that installs precisely
    the version the ceiling was written to exclude, and the disagreement stays
    invisible until someone regenerates — at which point versions move for
    reasons unrelated to whatever they were changing.

    Ceilings here are behavioural, not caution: `mcp<2` records that mcp 2.0.0
    removed `mcp.server.fastmcp`, the surface `veritas-mcp` is built on. A lock
    that ignores that bound ships an extra which cannot serve.
    """
    from packaging.requirements import Requirement
    from packaging.version import Version

    checked = 0
    for source, lock_path in (
        ("requirements.txt", RUNTIME_LOCK),
        ("requirements-dev.txt", DEV_LOCK),
    ):
        locked = _lock_entries(lock_path)
        for line in (REPO / source).read_text(encoding="utf-8").splitlines():
            line = line.split("#", 1)[0].strip()
            if not line or line.startswith("-r"):
                continue
            requirement = Requirement(line)
            key = requirement.name.lower().replace("_", "-")
            assert key in locked, (
                f"{key} is declared in {source} but absent from {lock_path.name}"
            )
            pinned = locked[key][0]
            # prereleases=True: the resolver legitimately pins a prerelease when
            # that is what satisfies the range, and rejecting them here would
            # fail on a lock that is correct.
            assert requirement.specifier.contains(Version(pinned), prereleases=True), (
                f"{lock_path.name} pins {key}=={pinned}, which {source} excludes "
                f"({requirement.specifier}). A bound changed without the lock being "
                "regenerated — run: python scripts/lock_requirements.py"
            )
            checked += 1

    assert checked, "no declared requirements were checked — the parser is wrong"


def test_lock_declares_the_platform_its_markers_came_from():
    """The lock is only correct for the environment that resolved it."""
    for path in (RUNTIME_LOCK, DEV_LOCK):
        header = path.read_text(encoding="utf-8")[:2000]
        assert "linux" in header, f"{path.name} must state the platform it targets"
        assert "3.12" in header, f"{path.name} must state the Python version it targets"


def test_lock_generator_refuses_to_run_off_target():
    """Fail-closed: a wrong lock cannot be generated, only refused."""
    lock_script = _load_script("lock_requirements")
    original = lock_script.TARGET_PLATFORM
    try:
        lock_script.TARGET_PLATFORM = "definitely-not-this-platform"
        with pytest.raises(SystemExit) as excinfo:
            lock_script._assert_on_target()
        assert excinfo.value.code == 1
    finally:
        lock_script.TARGET_PLATFORM = original


