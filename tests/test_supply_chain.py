"""Supply-chain pins: hashed lockfiles, SHA-pinned Actions, hard CI SBOM gate.

O.8 / O15. These tests pin local, reviewable artefacts only — not that an
install is uncompromised in the wild, and not that the Docker image path is
hash-locked (it still installs from pyproject floors).

Three things decay silently without a test:

1. **Every GitHub Action is pinned to a commit SHA.** A tag is a mutable
   pointer. ``release.yml`` runs with ``id-token: write`` — the PyPI Trusted
   Publishing identity — so whoever controls a tag at the moment a release
   runs can mint a token and publish as this project.

2. **Every package CI installs is pinned to a version and a SHA-256.** Floors
   (``>=``) make a green run a statement about one moment on PyPI rather than
   about the commit.

3. **The SBOM describes the published artifact, not the toolchain.** It is
   generated by ``cyclonedx-py`` against the clean venv the wheel is installed
   into, so it reports what ``pip install veritas-research`` actually produces.
   Generating it from the CI environment instead would over-report by ~100
   dev-only packages that never ship, and an SBOM with the wrong subject is
   worse than none — it invites a check that passes against the wrong list.

There is deliberately **one** SBOM generator. A second, lock-derived one was
written and removed during this change: a lock states what pip was *told* to
install, while ``cyclonedx-py`` reports what an environment *contains*, and two
artifacts both called "the SBOM" is the two-sources-of-truth failure this
repository forbids elsewhere.
"""

from __future__ import annotations

import importlib.util
import re
import shutil
import subprocess
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parent.parent
WORKFLOWS = REPO / ".github" / "workflows"
RUNTIME_LOCK = REPO / "requirements.lock"
DEV_LOCK = REPO / "requirements-dev.lock"

_USES_RE = re.compile(
    r"^\s*-?\s*uses:\s+(?P<action>[\w.-]+/[\w./-]+)@(?P<ref>\S+)(?P<rest>.*)$",
    re.MULTILINE,
)
_SHA_RE = re.compile(r"^[0-9a-f]{40}$")
_LOCK_ENTRY_RE = re.compile(
    r"^(?P<name>[A-Za-z0-9._-]+)==(?P<version>[^\s\\]+)\s*\\\s*\n"
    r"\s*--hash=sha256:(?P<digest>[0-9a-f]{64})\s*$",
    re.MULTILINE,
)


def _load_script(name: str):
    """Import a file from scripts/, which is not an importable package."""
    path = REPO / "scripts" / f"{name}.py"
    spec = importlib.util.spec_from_file_location(f"_veritas_script_{name}", path)
    assert spec and spec.loader, f"cannot load scripts/{name}.py"
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _workflow_files() -> list[Path]:
    files = sorted(WORKFLOWS.glob("*.yml")) + sorted(WORKFLOWS.glob("*.yaml"))
    assert files, "no workflow files found"
    return files


def _uses_entries() -> list[tuple[Path, str, str, str]]:
    entries = []
    for path in _workflow_files():
        for match in _USES_RE.finditer(path.read_text(encoding="utf-8")):
            entries.append(
                (path, match.group("action"), match.group("ref"), match.group("rest"))
            )
    assert entries, "no `uses:` references found — the parser is probably wrong"
    return entries


def _lock_entries(path: Path) -> dict[str, tuple[str, str]]:
    assert path.is_file(), f"missing lockfile: {path.name}"
    text = path.read_text(encoding="utf-8")
    entries = {
        m.group("name").lower().replace("_", "-"): (m.group("version"), m.group("digest"))
        for m in _LOCK_ENTRY_RE.finditer(text)
    }
    assert entries, f"{path.name} parsed to zero hash-pinned entries"
    return entries


def _version_tuple(version: str) -> tuple[int, ...]:
    return tuple(int(part) for part in re.findall(r"\d+", version)[:3])


# --------------------------------------------------------------------------
# 1. Actions are pinned to immutable commits
# --------------------------------------------------------------------------


def test_every_workflow_uses_is_full_commit_sha():
    """Every `uses:` must pin a full 40-char commit SHA (optional # version comment)."""
    unpinned = [
        f"{path.name}: {action}@{ref}"
        for path, action, ref, _ in _uses_entries()
        if not _SHA_RE.match(ref)
    ]
    assert not unpinned, (
        "GitHub Actions must be pinned to a full 40-character commit SHA, not a "
        "mutable tag or branch:\n  " + "\n  ".join(unpinned)
    )


def test_every_pinned_action_records_the_version_it_pins():
    """A bare SHA is unreviewable; the trailing comment says what it is."""
    missing = [
        f"{path.name}: {action}@{ref[:12]}"
        for path, action, ref, rest in _uses_entries()
        if not re.search(r"#\s*v?\d", rest)
    ]
    assert not missing, (
        "every pinned action needs a trailing `# vX.Y.Z` comment so the pin can "
        "be read and updated:\n  " + "\n  ".join(missing)
    )


def test_release_workflow_publish_step_is_pinned():
    """The one step that holds publishing authority, called out explicitly."""
    text = (WORKFLOWS / "release.yml").read_text(encoding="utf-8")
    match = re.search(r"uses:\s+pypa/gh-action-pypi-publish@(\S+)", text)
    assert match, "release.yml no longer uses pypa/gh-action-pypi-publish"
    assert _SHA_RE.match(match.group(1)), (
        "the PyPI publish step runs with id-token: write and must be pinned to a "
        f"commit SHA, found {match.group(1)!r}"
    )


