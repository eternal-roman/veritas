def test_release_job_does_not_combine_publish_identity_with_write_access():
    """Least privilege on the one job that can publish as this project.

    `id-token: write` mints the PyPI Trusted Publishing token. Adding
    `contents: write` to the same job — e.g. to attach an SBOM with
    `gh release upload` — would widen the blast radius of the most sensitive
    job in the repository.
    """
    text = (WORKFLOWS / "release.yml").read_text(encoding="utf-8")
    # This workflow's comments discuss `contents: write` in order to record why
    # it is absent, so the check must read directives, not prose.
    directives = "\n".join(
        line for line in text.splitlines() if not line.lstrip().startswith("#")
    )
    assert "id-token: write" in directives, "release.yml no longer uses Trusted Publishing"
    assert "contents: write" not in directives, (
        "the release job holds id-token: write; granting it contents: write too "
        "combines publishing authority with repository write access"
    )
    assert "gh release upload" not in directives, (
        "attaching to a release needs contents: write — keep it out of this job"
    )


def test_no_unhashed_dependency_install_remains_in_ci():
    """Every pip install either upgrades pip itself or verifies hashes.

    A single unhashed `pip install -r requirements-dev.txt` anywhere would
    quietly restore the floors-resolved-at-run-time behaviour the locks exist
    to remove.
    """
    offenders = []
    for path in _workflow_files():
        for line in path.read_text(encoding="utf-8").splitlines():
            stripped = line.strip()
            if not re.search(r"\bpip install\b", stripped) or stripped.startswith("#"):
                continue
            if "--require-hashes" in stripped:
                continue
            # Bootstrapping pip itself, and installing the just-built wheel,
            # are the two intended exceptions.
            if re.search(r"pip install --upgrade pip\s*$", stripped):
                continue
            if "dist/*.whl" in stripped:
                continue
            offenders.append(f"{path.name}: {stripped}")
    assert not offenders, "unhashed dependency installs remain:\n  " + "\n  ".join(offenders)
