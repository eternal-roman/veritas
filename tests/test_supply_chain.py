def test_ci_install_uses_require_hashes():
    """test + security-scan jobs must install via --require-hashes from the dev lock."""
    text = (WORKFLOWS / "ci.yml").read_text(encoding="utf-8")
    required = "pip install --require-hashes -r requirements-dev.lock"
    assert required in text, (
        "ci.yml must install with "
        f"{required!r} on the test and security-scan paths"
    )
    assert text.count(required) >= 2, (
        f"{required!r} must appear in both the test and security-scan install steps"
    )


def test_ci_sbom_step_is_hard_gate():
    """ci.yml must generate an SBOM and upload it; generation must not soft-fail."""
    text = (WORKFLOWS / "ci.yml").read_text(encoding="utf-8")
    lower = text.lower()
    assert "sbom" in lower, "ci.yml has no SBOM step"
    assert re.search(
        r"generate_sbom|cyclonedx|syft|cdxgen",
        text,
        re.IGNORECASE,
    ), "ci.yml SBOM step must invoke a known generator"
    assert re.search(
        r"upload-artifact|actions/upload-artifact@",
        text,
        re.IGNORECASE,
    ), "ci.yml must upload the SBOM as a workflow artifact"

    for match in re.finditer(r"(?is)([^\n]*sbom[^\n]*(?:\n[^\n]*){0,12})", text):
        block = match.group(0)
        assert "continue-on-error" not in block, (
            "SBOM path must not set continue-on-error:\n" + block
        )
        assert "|| true" not in block, "SBOM path must not soft-fail with || true:\n" + block
        assert "||true" not in block.replace(" ", ""), (
            "SBOM path must not soft-fail with ||true:\n" + block
        )


def test_bandit_remains_hard_gate_in_ci():
    """bandit -ll must stay a non-soft-fail CI step."""
    text = (WORKFLOWS / "ci.yml").read_text(encoding="utf-8")
    assert "bandit -r veritas scripts -ll -q" in text
    bandit_idx = text.index("bandit -r veritas scripts -ll -q")
    window = text[max(0, bandit_idx - 400) : bandit_idx + 120]
    assert "continue-on-error" not in window
    assert "|| true" not in window


